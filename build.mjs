// Builds the site into public_html/, the folder you upload to Hostinger.
// Usage: node build.mjs
import { copyFileSync, cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { createHash } from "node:crypto";
import { CATALOG } from "./src/catalog.mjs";
import { layout } from "./src/layout.mjs";
import { buildPages } from "./src/pages.mjs";

const OUT = "public_html";
// SITE_CONFIG lets you build with other details, for example to test before your real ones are ready.
const site = JSON.parse(readFileSync(process.env.SITE_CONFIG || "site.config.json", "utf8"));
const prices = JSON.parse(readFileSync("prices.json", "utf8"));
const version = createHash("sha1")
  .update(readFileSync("src/assets/style.css") + readFileSync("src/assets/book.js") + readFileSync("src/assets/site.js") + JSON.stringify(prices))
  .digest("hex")
  .slice(0, 8);
prices.__version = version;

// Whole winter = the one-time price for the same visits: visitsPerMonth x months.
const visits = prices.season.visitsPerMonth * prices.season.months;
const times = (o) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k, typeof v === "object" ? times(v) : v * visits]));
prices.winter = times(prices.once);

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
cpSync("src/assets", join(OUT, "assets"), { recursive: true });

const pages = buildPages(site, prices);
for (const page of pages) {
  const file = page.file ? join(OUT, page.file) : join(OUT, page.path, "index.html");
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, layout(site, { ...page, version }));
}

// The booking handler and what it needs. config.php holds the private booking email.
mkdirSync(join(OUT, "api"), { recursive: true });
copyFileSync("src/api/book.php", join(OUT, "api/book.php"));
const winterDesc = CATALOG.plan.winter.label;
const labels = {
  plan: { once: CATALOG.plan.once.label, winter: winterDesc },
  driveway: Object.fromEntries(Object.entries(CATALOG.driveway).map(([k, v]) => [k, v.label])),
  sidewalk: Object.fromEntries(Object.entries(CATALOG.sidewalk).map(([k, v]) => [k, v.label])),
  walkway: Object.fromEntries(Object.entries(CATALOG.walkway).map(([k, v]) => [k, v.label])),
};
writeFileSync(join(OUT, "api/catalog.json"), JSON.stringify({ gst: prices.gst, prices: { once: prices.once, winter: prices.winter }, labels }, null, 2));
const php = (s) => `'${String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
writeFileSync(
  join(OUT, "api/config.php"),
  `<?php\n// Generated by build.mjs from site.config.json. Do not edit here.\nreturn [\n  'siteName' => ${php(site.name)},\n  'phone' => ${php(site.phone)},\n  'bookingEmail' => ${php(site.bookingEmail)},\n  'fromEmail' => ${php(site.fromEmail)},\n];\n`,
);
writeFileSync(join(OUT, "api/.htaccess"), `Options -Indexes\n<FilesMatch "\\.(json|txt|jsonl)$">\n  Require all denied\n</FilesMatch>\n`);

// Search engines.
const base = site.siteUrl.replace(/\/$/, "");
const indexable = pages.filter((p) => !p.noindex);
writeFileSync(
  join(OUT, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${indexable
    .map((p) => `  <url><loc>${base}${p.path}</loc></url>`)
    .join("\n")}\n</urlset>\n`,
);
writeFileSync(
  join(OUT, "robots.txt"),
  site.preview
    ? "# Preview copy: keep it out of search results.\nUser-agent: *\nDisallow: /\n"
    : `User-agent: *\nDisallow: /api/\nDisallow: /thank-you/\n\nSitemap: ${base}/sitemap.xml\n`,
);

writeFileSync(
  join(OUT, ".htaccess"),
  `# ClearLot YQR
Options -Indexes
ErrorDocument 404 /404.html
DirectoryIndex index.html index.php

# Send everyone to https.
RewriteEngine On
RewriteCond %{HTTPS} off
RewriteCond %{HTTP:X-Forwarded-Proto} !https
RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]

<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType text/css "access plus 1 year"
  ExpiresByType application/javascript "access plus 1 year"
  ExpiresByType font/woff2 "access plus 1 year"
  ExpiresByType image/svg+xml "access plus 1 month"
  ExpiresByType image/png "access plus 1 month"
  ExpiresByType text/html "access plus 0 seconds"
</IfModule>
<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript image/svg+xml application/json
</IfModule>
`,
);

const missing = ["phone", "bookingEmail", "fromEmail"].filter((k) => !site[k]);
console.log(`Built ${pages.length} pages into ${OUT}/`);
if (missing.length) console.warn(`WARNING: site.config.json is missing ${missing.join(", ")}. Fill these in before launch.`);
console.log(`Whole winter priced as ${visits} visits (${prices.season.visitsPerMonth} a month for ${prices.season.months} months).`);
